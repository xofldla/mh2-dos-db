foreach ($name in $icons.Keys) {
  $d = $icons[$name]; $sb = New-Object Text.StringBuilder
  $pal = New-Object 'System.Collections.Generic.Dictionary[string,string]'([StringComparer]::Ordinal)
  foreach ($kv in $d.pal.Split(';')) { $q = $kv.Split('='); $pal[$q[0]] = $q[1] }
  [void]$sb.Append('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">')
  for ($y = 0; $y -lt 16; $y++) { $row = $d.px[$y]; for ($x = 0; $x -lt 16; $x++) { $c = [string]$row[$x]; if ($c -ne '.' -and $pal.ContainsKey($c)) { [void]$sb.Append("<rect x=`"$x`" y=`"$y`" width=`"1`" height=`"1`" fill=`"$($pal[$c])`"/>") } } }
  [void]$sb.Append('</svg>')
  [IO.File]::WriteAllText("$out\$name.svg", $sb.ToString(), (New-Object Text.UTF8Encoding $false))
}
